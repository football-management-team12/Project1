import assert from "node:assert/strict";
import { bookingNeedsCollection, bookingDisplayStatus, bookingBalance } from "../frontend/src/utils/bookingStatus.js";
const booking = { Status: "CONFIRMED", AttendanceState: "CHECKED_IN", BookingDate: "2026-11-16", StartTime: "10:31", EndTime: "11:04", TotalAmount: 500000, TotalPaidAmount: 100000 };
const start = Date.parse("2026-11-16T10:31:00+07:00");
const end = Date.parse("2026-11-16T11:04:00+07:00");
assert.equal(bookingDisplayStatus(booking, start-1), "CONFIRMED");
assert.equal(bookingDisplayStatus({...booking,TotalPaidAmount:500000}, start-1), "CONFIRMED");
assert.equal(bookingDisplayStatus(booking, start), "IN_PROGRESS");
assert.equal(bookingDisplayStatus(booking, end), "ENDED");
assert.equal(bookingDisplayStatus({...booking,Status:"COMPLETED"},end),"ENDED");
assert.equal(bookingDisplayStatus({...booking,Status:"COMPLETED",TotalPaidAmount:500000},end),"COMPLETED");
assert.equal(bookingDisplayStatus({...booking,TotalPaidAmount:500000},end),"COMPLETED");
assert.equal(bookingDisplayStatus({...booking,TotalPaidAmount:500000},end-1),"IN_PROGRESS");
assert.equal(bookingDisplayStatus({...booking,Status:"COMPLETED",TotalPaidAmount:500000},end-1),"IN_PROGRESS");
assert.equal(bookingDisplayStatus({...booking,TotalPaidAmount:500000,RefundedAmount:1},end),"ENDED");
assert.equal(bookingDisplayStatus({...booking,TotalPaidAmount:500000,AttendanceState:"NO_SHOW"},end),"NO_SHOW");
assert.equal(bookingNeedsCollection(booking,start-1),false);
assert.equal(bookingNeedsCollection(booking,start),true);
assert.equal(bookingNeedsCollection(booking,end),true);
assert.equal(bookingNeedsCollection({...booking,TotalPaidAmount:500000},start),false);
assert.equal(bookingNeedsCollection({...booking,Status:"CANCELLED"},start),false);
assert.equal(bookingNeedsCollection({...booking,Status:"PENDING"},start),false);
assert.equal(bookingNeedsCollection({...booking,TotalAmount:0,TotalPaidAmount:0},start),false);
assert.equal(bookingNeedsCollection({...booking,TotalPaidAmount:500000,RefundedAmount:100000},start),true);
assert.equal(bookingBalance({...booking,TotalPaidAmount:500000}).remaining,0);
assert.equal(bookingBalance({...booking,TotalPaidAmount:500000,RefundedAmount:100000}).remaining,100000);
assert.equal(bookingBalance({...booking,TotalAmount:null}).valid,false);
assert.equal(bookingDisplayStatus({...booking,AttendanceState:null},start),"IN_PROGRESS");
assert.equal(bookingDisplayStatus({...booking,Status:"CANCELLED",AttendanceState:"NO_SHOW"},start),"NO_SHOW");
assert.equal(bookingBalance({...booking,Status:"CANCELLED",AttendanceState:"NO_SHOW"}).remaining,0);
console.log("PASS: lifecycle, payment, early prepayment, schedule boundaries, refunds and completion are independent");
